export enum LogAction {
  // yaşam döngüsü
  REQUEST_RECEIVED = 'REQUEST_RECEIVED', // metot çağrıldı
  REQUEST_SUCCESS = 'REQUEST_SUCCESS', // metot hatasız bitti

  // client hataları (4xx)
  VALIDATION_FAILED = 'VALIDATION_FAILED', // BAD_REQUEST, UNPROCESSABLE_ENTITY, VALIDATION_ERROR
  UNAUTHORIZED = 'UNAUTHORIZED', // UNAUTH, TOKEN_EXPIRED, INVALID_TOKEN, PASSWORD_OR_EMAIL_WRONG
  FORBIDDEN = 'FORBIDDEN', // FORBIDDEN, USER_TYPE_NOT_VALID_FOR_REGISTER, ACCOUNT_DISABLED
  NOT_FOUND = 'NOT_FOUND', // NOT_FOUND
  CONFLICT = 'CONFLICT', // CONFLICT, EMAIL_ALREADY_EXISTS, PHONE_ALREADY_EXISTS, TAX_NUMBER_ALREADY_EXISTS
  RATE_LIMITED = 'RATE_LIMITED', // TOO_MANY_REQUESTS

  // sunucu/altyapı hataları (5xx)
  DEPENDENCY_FAILED = 'DEPENDENCY_FAILED', // BAD_GATEWAY, SERVICE_UNAVAILABLE — başka bir servise yapılan çağrı patladı
  INTERNAL_ERROR = 'INTERNAL_ERROR', // INTERNAL_SERVER_ERROR

  // bilinmeyen durum
  REQUEST_FAILED = 'REQUEST_FAILED', // enum'da karşılığı olmayan / normalize edilemeyen hata
}
